"""run-ingestion: gated execution of generated COPY INTO / Auto Loader jobs.

F17 -- `generate-ingestion` emitted 12 runnable jobs and the platform had no
governed way to run them, so landing data meant reaching for the raw vendor CLI
and routing around AUTORESEARCH_ALLOW_REMOTE_EXECUTION. These tests pin the same
refusal ladder `apply-provisioning` already proves.
"""
from __future__ import annotations

